import java.io.*;
import java.lang.reflect.*;
import java.net.*;
import java.nio.file.*;
import java.util.*;
import java.util.jar.*;

/**
 * Writes WebBuildTypes.java: for every block class that declares a building class, a factory that
 * creates it. Block.initBuilding finds these by reflection (getDeclaredClasses), which the browser
 * build doesn't have. Usage: java GenBuildTypes.java <out.java> <core jar> <classpath jars...>
 */
public class GenBuildTypes{
    public static void main(String[] args) throws Exception{
        List<URL> urls = new ArrayList<>();
        for(int i = 1; i < args.length; i++) urls.add(new File(args[i]).toURI().toURL());
        ClassLoader loader = new URLClassLoader(urls.toArray(new URL[0]), null);
        Class<?> block = Class.forName("mindustry.world.Block", false, loader);
        Class<?> building = Class.forName("mindustry.gen.Building", false, loader);

        TreeMap<String, String> entries = new TreeMap<>();
        try(JarFile jar = new JarFile(args[1])){
            for(JarEntry e : Collections.list(jar.entries())){
                String n = e.getName();
                if(!n.endsWith(".class") || !n.startsWith("mindustry/")) continue;
                Class<?> c;
                try{
                    c = Class.forName(n.substring(0, n.length() - 6).replace('/', '.'), false, loader);
                }catch(Throwable t){
                    continue;
                }
                if(!block.isAssignableFrom(c) || c.isAnonymousClass() || !Modifier.isPublic(c.getModifiers())) continue;
                Class<?> type = null;
                for(Class<?> inner : c.getDeclaredClasses()){
                    if(building.isAssignableFrom(inner) && !inner.isInterface()){
                        type = inner;
                        break;
                    }
                }
                if(type == null) continue;
                String blockName = c.getName().replace('$', '.');
                if(Modifier.isAbstract(type.getModifiers()) || !Modifier.isPublic(type.getModifiers()) || Modifier.isStatic(type.getModifiers())){
                    //same outcome as the reflective lookup: no usable constructor
                    entries.put(c.getName(), "        map.put(" + blockName + ".class, null);");
                    continue;
                }
                entries.put(c.getName(), "        map.put(" + blockName + ".class, b -> ((" + blockName + ")b).new " + type.getSimpleName() + "());");
            }
        }

        StringBuilder out = new StringBuilder();
        out.append("package mindustry.web;\n\n")
            .append("import arc.func.*;\nimport mindustry.gen.*;\nimport mindustry.world.*;\n\nimport java.util.*;\n\n")
            .append("/** Generated by GenBuildTypes.java: the building class each block declares. */\n")
            .append("public class WebBuildTypes{\n")
            .append("    static final HashMap<Class<?>, Func<Block, Building>> map = new HashMap<>();\n\n")
            .append("    /** @return a factory for the first building class declared by the block's class or its superclasses. */\n")
            .append("    public static Prov<Building> get(Block block){\n")
            .append("        for(Class<?> c = block.getClass(); c != null && Block.class.isAssignableFrom(c); c = c.getSuperclass()){\n")
            .append("            if(map.containsKey(c)){\n")
            .append("                Func<Block, Building> f = map.get(c);\n")
            .append("                return f == null ? null : () -> f.get(block);\n")
            .append("            }\n")
            .append("        }\n")
            .append("        return null;\n")
            .append("    }\n\n")
            .append("    static{\n");
        for(String line : entries.values()) out.append(line).append('\n');
        out.append("    }\n}\n");
        Files.writeString(Path.of(args[0]), out.toString());
        System.out.println(entries.size() + " block classes");
    }
}
