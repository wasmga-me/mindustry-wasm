#!/usr/bin/env python3
"""Turns the jnigen-style natives of an Arc class into a wasm build.

For a Java file whose native methods carry their C/C++ body in a comment (jnigen style),
writes:
  - <out>.cpp: one exported C function per native, compiled with emscripten;
  - a Java copy of the class (package moved to --package) where each native calls the
    function through window.arcNatives, the emscripten module the page loads first.

Pointers (Java long) are 32-bit in wasm. Arrays, strings and buffers are copied into the
wasm heap for the call; buffers named in --keep stay there (FreeType keeps font data).
"""
import argparse
import re

NATIVE = re.compile(
    r'^([ \t]*)((?:(?:public|private|protected|static|native|final)\s+)+)([\w\[\].]+)\s+(\w+)\s*\(([^)]*)\)\s*;[ \t]*/\*(MANUAL)?(.*?)\*/',
    re.S | re.M)
JNI_BLOCK = re.compile(r'/\*JNI(.*?)\*/', re.S)

C_TYPES = {
    'void': 'void', 'int': 'jint', 'long': 'jlong', 'float': 'jfloat', 'double': 'jdouble',
    'boolean': 'jboolean', 'short': 'jshort', 'byte': 'jbyte', 'char': 'jchar',
    'String': 'char*', 'byte[]': 'char*', 'boolean[]': 'char*', 'short[]': 'short*',
    'char[]': 'unsigned short*', 'int[]': 'int*', 'float[]': 'float*', 'double[]': 'double*',
    'Buffer': 'unsigned char*', 'ByteBuffer': 'unsigned char*', 'FloatBuffer': 'unsigned char*',
    'ShortBuffer': 'unsigned char*', 'IntBuffer': 'unsigned char*',
}
RETURN_C = {'String': 'jstring', 'ByteBuffer': 'jobject'}
ARRAY_JS = {'byte[]': 'HEAP8', 'boolean[]': 'HEAP8', 'short[]': 'HEAP16', 'char[]': 'HEAPU16',
            'int[]': 'HEAP32', 'float[]': 'HEAPF32', 'double[]': 'HEAPF64'}
ELEM = {'HEAP8': 1, 'HEAP16': 2, 'HEAPU16': 2, 'HEAP32': 4, 'HEAPF32': 4, 'HEAPF64': 8}


def class_stack_at(text, pos):
    """Names of the classes enclosing pos, outermost first (skips comments and strings)."""
    stack = []
    pending = None
    i = 0
    depth = 0
    while i < pos:
        c = text[i]
        if text.startswith('/*', i):
            i = text.find('*/', i + 2) + 2
            continue
        if text.startswith('//', i):
            i = text.find('\n', i)
            continue
        if c == '"' or c == "'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == '\\' else 1
            i = j + 1
            continue
        m = re.match(r'(?:class|interface|enum)\s+(\w+)', text[i:i + 200])
        if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == '_')):
            pending = m.group(1)
            i += m.end()
            continue
        if c == '{':
            depth += 1
            stack.append((pending, depth))
            pending = None
        elif c == '}':
            stack.pop()
            depth -= 1
        i += 1
    return [name for name, _ in stack if name]


def parse_params(params):
    out = []
    for p in params.split(','):
        p = p.strip()
        if not p:
            continue
        t, n = p.rsplit(None, 1)
        out.append((t.replace('final ', '').strip(), n))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('java')
    ap.add_argument('--package', required=True)
    ap.add_argument('--java-out', required=True)
    ap.add_argument('--cpp-out', required=True)
    ap.add_argument('--keep', default='', help='comma-separated Class.method.param buffers left in the heap')
    ap.add_argument('--override', action='append', default=[],
                    help='Class.method=java body used instead of a native call')
    ap.add_argument('--skip', default='', help='comma-separated Class.method natives left as throwing stubs')
    args = ap.parse_args()

    keep = set(filter(None, args.keep.split(',')))
    skip = set(filter(None, args.skip.split(',')))
    overrides = dict(o.split('=', 1) for o in args.override)
    src = open(args.java).read()
    orig_pkg = re.search(r'^package\s+([\w.]+);', src, re.M).group(1)

    header = '\n'.join(JNI_BLOCK.findall(src))
    cpp = ['// generated by jni2wasm.py from ' + args.java.split('/')[-1], '#include "jni_shim.h"', header, 'extern "C" {']

    out = []
    last = 0
    names = {}
    for m in NATIVE.finditer(src):
        indent, mods, ret, name, params, manual, body = m.groups()
        if 'native' not in mods.split():
            continue
        cls = '_'.join(class_stack_at(src, m.start()))
        key = cls.split('_')[-1] + '.' + name
        params = parse_params(params)
        cname = cls + '_' + name
        names[cname] = names.get(cname, 0) + 1
        if names[cname] > 1:
            cname += str(names[cname])
        jmods = ' '.join(x for x in mods.split() if x != 'native')
        out.append(src[last:m.start()])
        last = m.end()

        sig = ', '.join(t + ' ' + n for t, n in params)
        if key in overrides:
            out.append(f'{indent}{jmods} {ret} {name}({sig}){{\n{indent}    {overrides[key]}\n{indent}}}')
            continue
        if manual or key in skip:
            out.append(f'{indent}{jmods} {ret} {name}({sig}){{\n{indent}    throw new UnsupportedOperationException("{key}");\n{indent}}}')
            continue

        # C side
        cparams = []
        locals_ = []
        for t, n in params:
            cparams.append(f'{C_TYPES[t]} {n}')
            if ('obj_' + n) in body:
                locals_.append(f'jobject obj_{n} = 0;')
        cret = RETURN_C.get(ret, C_TYPES.get(ret))
        cpp.append(f'EMSCRIPTEN_KEEPALIVE {cret} {cname}({", ".join(cparams)}){{')
        cpp.append('    JNIEnv* env = &jni_env; (void)env;')
        cpp += ['    ' + l for l in locals_]
        cpp.append(body.rstrip())
        cpp.append('}')

        # JS bridge
        jsparams, jsargs, prep, post, callargs = [], [], [], [], []
        for t, n in params:
            if t == 'long':
                jsparams.append(f'int {n}')
                jsargs.append(f'(int){n}')
                callargs.append(n)
            elif t == 'String':
                jsparams.append(f'String {n}')
                jsargs.append(n)
                prep.append(f'var p_{n} = {n} == null ? 0 : M.stringToNewUTF8({n});')
                post.append(f'M._free(p_{n});')
                callargs.append(f'p_{n}')
            elif t in ARRAY_JS:
                heap = ARRAY_JS[t]
                jsparams.append(f'@JSByRef {t} {n}')
                jsargs.append(n)
                size = f'{n}.length * {ELEM[heap]}'
                prep.append(f'var p_{n} = M._malloc({size} || 1); M.{heap}.set({n}, p_{n} / {ELEM[heap]});')
                post.append(f'{n}.set(M.{heap}.subarray(p_{n} / {ELEM[heap]}, p_{n} / {ELEM[heap]} + {n}.length)); M._free(p_{n});')
                callargs.append(f'p_{n}')
            elif t.endswith('Buffer'):
                jsparams.append(f'@JSBuffer(JSBufferType.UINT8) java.nio.Buffer {n}')
                jsargs.append(n)
                prep.append(f'var p_{n} = M._malloc({n}.length || 1); M.HEAPU8.set({n}, p_{n});')
                if f'{key}.{n}' not in keep:
                    post.append(f'{n}.set(M.HEAPU8.subarray(p_{n}, p_{n} + {n}.length)); M._free(p_{n});')
                callargs.append(f'p_{n}')
            else:
                jsparams.append(f'{t} {n}')
                jsargs.append(n)
                callargs.append(n)

        jsret = {'long': 'int', 'ByteBuffer': 'org.teavm.jso.typedarrays.Int8Array'}.get(ret, ret)
        conv = {
            'void': '', 'boolean': 'return !!r;', 'String': 'return r ? M.UTF8ToString(r) : null;',
            'ByteBuffer': 'return r ? M.HEAP8.slice(r, r + M._jni_buffer_size()) : null;',
        }.get(ret, 'return r;')
        script = 'var M = window.arcNatives; ' + ' '.join(prep) + f' var r = M._{cname}({", ".join(callargs)}); ' + ' '.join(post) + ' ' + conv
        script = script.replace('\\', '\\\\').replace('"', '\\"')
        bridge = f'{name}$wasm'
        throws = 'ThrowNew' in body or 'throwError' in body

        call = f'{bridge}({", ".join(jsargs)})'
        lines = []
        if ret == 'void':
            lines.append(f'{call};')
        elif ret == 'long':
            lines.append(f'long result = {call};')
        elif ret == 'ByteBuffer':
            lines.append(f'org.teavm.jso.typedarrays.Int8Array data = {call};')
            lines.append('java.nio.ByteBuffer result = data == null ? null : java.nio.ByteBuffer.wrap(data.toJavaArray()).order(java.nio.ByteOrder.nativeOrder());')
        else:
            lines.append(f'{ret} result = {call};')
        if throws:
            lines.append('String error = jni$error(); if(error != null) throw new arc.util.ArcRuntimeException(error);')
        if ret != 'void':
            lines.append('return result;')
        body_java = ''.join(f'\n{indent}    {l}' for l in lines)
        out.append(f'{indent}{jmods} {ret} {name}({sig}){{{body_java}\n{indent}}}\n\n'
                   f'{indent}@org.teavm.jso.JSBody(params = {{{", ".join(chr(34) + n + chr(34) for t, n in params)}}}, script = "{script}")\n'
                   f'{indent}private static native {jsret} {bridge}({", ".join(jsparams)});')

    out.append(src[last:])
    java = ''.join(out)
    helper = ('\n    @org.teavm.jso.JSBody(script = "var M = window.arcNatives; var e = M._jni_take_error(); return e ? M.UTF8ToString(e) : null;")\n'
              '    static native String jni$error();\n')
    # insert the helper right after the top-level class opening brace
    top = re.search(r'^public (?:final )?class \w+[^{]*\{', java, re.M)
    java = java[:top.end()] + helper + java[top.end():]
    java = re.sub(r'^package\s+[\w.]+;', f'package {args.package};\n\nimport {orig_pkg}.*;\nimport org.teavm.jso.*;', java, count=1, flags=re.M)
    open(args.java_out, 'w').write(java)

    cpp.append('}')
    open(args.cpp_out, 'w').write('\n'.join(cpp) + '\n')


if __name__ == '__main__':
    main()
